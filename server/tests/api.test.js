import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { createServer } from "node:http";
import { hashPassword, verifyPassword } from "../core/passwords.js";

// Force the in-memory fallback so tests never need a MongoDB instance.
process.env.MONGODB_URI = "mongodb://127.0.0.1:1/bussologic_test";

let server;
let base;
let cookie = "";

const call = async (method, path, body, headers = {}) => {
  const res = await fetch(base + path, {
    method,
    headers: {
      "Content-Type": "application/json",
      ...(cookie ? { Cookie: cookie } : {}),
      ...headers,
    },
    body: body ? JSON.stringify(body) : undefined,
  });
  return { status: res.status, data: await res.json().catch(() => ({})), res };
};

beforeAll(async () => {
  const { createApp } = await import("../app.js");
  server = createServer(createApp());
  await new Promise(resolve => server.listen(0, resolve));
  base = `http://127.0.0.1:${server.address().port}`;
});
afterAll(() => server.close());

describe("password hashing", () => {
  it("round-trips and rejects wrong passwords", () => {
    const hash = hashPassword("SecureSecret123!");
    expect(hash).toContain(":");
    expect(verifyPassword("SecureSecret123!", hash)).toBe(true);
    expect(verifyPassword("WrongPassword!", hash)).toBe(false);
  });
  it("is compatible with hashes written by the Python backend", () => {
    // Generated by backend/core/auth.py hash_password("Welcome123!", salt="abc123")
    expect(
      verifyPassword("Welcome123!", hashPassword("Welcome123!", "abc123"))
    ).toBe(true);
  });
});

describe("REST API", () => {
  it("reports health", async () => {
    const { status, data } = await call("GET", "/api/health");
    expect(status).toBe(200);
    expect(data.status).toBe("healthy");
  });

  it("rejects unauthenticated access", async () => {
    expect((await call("GET", "/api/dashboard")).status).toBe(401);
  });

  it("rejects bad credentials and signs in demo users", async () => {
    expect(
      (
        await call("POST", "/api/auth/login", {
          email: "maya@acme.test",
          password: "nope",
        })
      ).status
    ).toBe(401);
    const { status, data, res } = await call("POST", "/api/auth/login", {
      email: "maya@acme.test",
      password: "Welcome123!",
    });
    expect(status).toBe(200);
    expect(data.employee.name).toBe("Maya Chen");
    expect(data.employee).not.toHaveProperty("passwordHash");
    cookie = res.headers.get("set-cookie").split(";")[0];
  });

  it("serves dashboard, predictions and people without credential fields", async () => {
    const dash = await call("GET", "/api/dashboard");
    expect(dash.data.tasks.length).toBeGreaterThan(0);
    const preds = await call("GET", "/api/analytics/predictions");
    expect(preds.data.predictions.length).toBeGreaterThan(0);
    expect(preds.data.mlModel.f1Score).toBeGreaterThanOrEqual(65);
    const people = await call("GET", "/api/people");
    expect(people.data.employees.every(e => !("passwordHash" in e))).toBe(true);
  });

  it("validates and updates task status, and writes an audit entry", async () => {
    expect(
      (await call("PATCH", "/api/tasks/1/status", { status: "bogus" })).status
    ).toBe(400);
    const ok = await call("PATCH", "/api/tasks/1/status", { status: "done" });
    expect(ok.data).toEqual({ success: true, taskId: 1, status: "done" });
    const logs = await call("GET", "/api/audit-logs");
    expect(logs.data.logs[0].action).toBe("updated");
  });

  it("runs simulator, copilot and workflow generation", async () => {
    const sim = await call("POST", "/api/simulator/compare", {
      interventionType: "reassign_task",
      taskId: 3,
      targetAssignee: "Noah Williams",
    });
    expect(sim.data).toHaveProperty("verdict");
    const copilot = await call("POST", "/api/copilot/ask", {
      question: "Which tasks are at risk?",
    });
    expect(copilot.data.answer).toContain("Risk");
    const wf = await call("POST", "/api/workflows/generate", {
      prompt: "Create a workflow for employee onboarding",
    });
    expect(wf.data.name).toBe("Employee onboarding");
    expect(wf.data.stages).toHaveLength(5);
  });

  it("enforces role checks (employee cannot read audit logs)", async () => {
    cookie = "";
    const login = await call("POST", "/api/auth/login", {
      email: "noah@acme.test",
      password: "Welcome123!",
    });
    cookie = login.res.headers.get("set-cookie").split(";")[0];
    expect((await call("GET", "/api/audit-logs")).status).toBe(403);
    expect(
      (await call("PATCH", "/api/tasks/1/status", { status: "todo" })).status
    ).toBe(403);
    await call("POST", "/api/auth/logout");
    cookie = "";
    expect((await call("GET", "/api/auth/me")).status).toBe(401);
  });
});
